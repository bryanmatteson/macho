#[test]
fn cpp_report_validation_rejects_a_guessed_declaration_without_its_receipts() {
    let path = support::temp_file_path("cpp-cli-receipt-validation");
    std::fs::write(&path, cpp_fixture()).expect("write fixture");
    let output = support::run_cli([
        "cpp",
        path.to_str().unwrap(),
        "--headers",
        "--projection-policy",
        "best-effort",
        "--format",
        "json",
    ]);
    let _ = std::fs::remove_file(path);
    assert!(output.status.success());
    let envelope: serde_json::Value = serde_json::from_slice(&output.stdout).unwrap();
    let mut report: macho::analysis::report::RecoveryReport =
        serde_json::from_value(envelope["data"].clone()).unwrap();
    let mut mismatched_choice = report.clone();
    let declaration = mismatched_choice.slices.as_mut_slice()[0]
        .header
        .as_mut()
        .unwrap()
        .declarations
        .iter_mut()
        .find(|declaration| {
            matches!(
                declaration,
                macho::analysis::report::HeaderDecl::Function {
                    owner: Some(owner),
                    ..
                } if owner.terminal_kind() == macho::analysis::report::HeaderOwnerKind::Class
            )
        })
        .expect("best-effort fixture projects a selected class owner");
    let macho::analysis::report::HeaderDecl::Function {
        owner: Some(owner), ..
    } = declaration
    else {
        unreachable!("filtered to a function with an owner")
    };
    *owner.scope_kinds.as_mut_slice().last_mut().unwrap() =
        macho::analysis::report::HeaderOwnerKind::Namespace;
    owner.member_access = None;
    assert!(mismatched_choice.validate().is_err());

    report.slices.as_mut_slice()[0]
        .header
        .as_mut()
        .unwrap()
        .assumption_ledger
        .selections
        .clear();
    assert!(report.validate().is_err());

    let mut source_tamper: macho::analysis::report::RecoveryReport =
        serde_json::from_value(envelope["data"].clone()).unwrap();
    source_tamper.slices.as_mut_slice()[0]
        .header
        .as_mut()
        .unwrap()
        .source
        .push_str("int fabricated_without_a_receipt();\n");
    assert!(source_tamper.validate().is_err());
}

