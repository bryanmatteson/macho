#[test]
fn cpp_explicit_hypothesis_selections_accept_inline_json_and_toml_input() {
    let path = support::temp_file_path("cpp-cli-explicit-hypotheses");
    std::fs::write(&path, cpp_fixture()).expect("write fixture");
    let discovery = support::run_cli([
        "cpp",
        path.to_str().unwrap(),
        "--headers",
        "--projection-policy",
        "best-effort",
        "--format",
        "json",
    ]);
    assert!(discovery.status.success());
    let discovery: serde_json::Value = serde_json::from_slice(&discovery.stdout).unwrap();
    let hypotheses = discovery["data"]["slices"][0]["header"]["assumption_ledger"]["hypotheses"]
        .as_array()
        .unwrap();
    let selection = |candidate_id: &str| {
        let hypothesis = hypotheses
            .iter()
            .find(|hypothesis| {
                hypothesis["candidates"]
                    .as_array()
                    .unwrap()
                    .iter()
                    .any(|candidate| candidate["id"] == candidate_id)
            })
            .unwrap();
        format!(
            "{}={candidate_id}",
            hypothesis["subject"]["key"].as_str().unwrap()
        )
    };
    let owner_selection = selection("class_owner_public");
    let return_selection = selection("opaque_return_type");
    let owner_key = owner_selection.split_once('=').unwrap().0.to_owned();
    let return_key = return_selection.split_once('=').unwrap().0.to_owned();
    let inline_output = support::run_cli(vec![
        "cpp".to_owned(),
        path.to_string_lossy().into_owned(),
        "--headers".to_owned(),
        "--hypothesis-selection".to_owned(),
        owner_selection,
        "--hypothesis-selection".to_owned(),
        return_selection,
        "--format".to_owned(),
        "json".to_owned(),
    ]);
    assert!(
        inline_output.status.success(),
        "{}",
        String::from_utf8_lossy(&inline_output.stderr)
    );

    let selection_path =
        support::temp_file_path("cpp-cli-hypothesis-selections").with_extension("json");
    std::fs::write(
        &selection_path,
        serde_json::to_vec_pretty(&serde_json::json!({
            "schema_version": 1,
            "selections": [
                {
                    "subject": {"domain": "cpp_header", "key": owner_key},
                    "candidate_id": "class_owner_public"
                },
                {
                    "subject": {"domain": "cpp_header", "key": return_key},
                    "candidate_id": "opaque_return_type"
                }
            ]
        }))
        .unwrap(),
    )
    .expect("write selection document");
    let json_output = support::run_cli([
        "cpp",
        path.to_str().unwrap(),
        "--headers",
        "--hypothesis-selection-file",
        selection_path.to_str().unwrap(),
        "--format",
        "json",
    ]);
    let _ = std::fs::remove_file(selection_path);
    assert!(
        json_output.status.success(),
        "{}",
        String::from_utf8_lossy(&json_output.stderr)
    );

    let toml_path = support::temp_file_path("cpp-cli-hypothesis-selections").with_extension("toml");
    std::fs::write(
        &toml_path,
        format!(
            r#"[selections.cpp_header]
"{owner_key}" = "class_owner_public"
"{return_key}" = "opaque_return_type"
"#
        ),
    )
    .expect("write TOML selection document");
    let toml_output = support::run_cli([
        "cpp",
        path.to_str().unwrap(),
        "--headers",
        "--hypothesis-selection-file",
        toml_path.to_str().unwrap(),
        "--format",
        "json",
    ]);
    let _ = std::fs::remove_file(path);
    let _ = std::fs::remove_file(toml_path);
    assert!(
        toml_output.status.success(),
        "{}",
        String::from_utf8_lossy(&toml_output.stderr)
    );

    let inline_report: serde_json::Value = serde_json::from_slice(&inline_output.stdout).unwrap();
    let json_report: serde_json::Value = serde_json::from_slice(&json_output.stdout).unwrap();
    let toml_report: serde_json::Value = serde_json::from_slice(&toml_output.stdout).unwrap();
    for report in [&inline_report, &json_report, &toml_report] {
        let header = &report["data"]["slices"][0]["header"];
        assert!(header["source"].as_str().unwrap().contains("class Demo"));
        let receipts = header["assumption_ledger"]["selections"]
            .as_array()
            .unwrap();
        assert_eq!(receipts.len(), 2);
        assert!(
            receipts
                .iter()
                .any(|receipt| { receipt["chosen_candidate_id"] == "class_owner_public" })
        );
        assert!(
            receipts
                .iter()
                .any(|receipt| receipt["chosen_candidate_id"] == "opaque_return_type")
        );
        for receipt in receipts {
            assert_eq!(receipt["operator_policy"], "strict");
            assert_eq!(receipt["decision_authority"], "explicit_operator_choice");
            assert_eq!(receipt["explicitly_chosen"], true);
        }
    }
    assert_eq!(
        inline_report["data"]["slices"][0]["header"],
        json_report["data"]["slices"][0]["header"]
    );
    assert_eq!(
        inline_report["data"]["slices"][0]["header"],
        toml_report["data"]["slices"][0]["header"]
    );
}

